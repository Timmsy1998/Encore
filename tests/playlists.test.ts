import { describe, expect, it } from "vitest";
import { CommandSchema, defaults, key, migrate, type Track } from "../src/core/contracts";
import { Playlists } from "../src/core/playlists";
import { Queue } from "../src/core/queue";
const id = "11111111-1111-4111-8111-111111111111";
const otherId = "22222222-2222-4222-8222-222222222222";
const spotify: Track = { id: "a".repeat(22), source: "spotify", title: "Spotify song", author: "Artist", duration: 180, user: "Viewer" };
const youtube: Track = { ...spotify, id: "abcdefghijk", source: "youtube", title: "YouTube song" };
describe("saved mixed playlists", () => {
  it("keeps mixed songs and imports, deduplicates provider IDs, and persists library ordering independently of rotation", () => {
    const q = new Queue();
    const library = new Playlists(q.state);
    library.create(id, " Stream music ");
    library.append(id, [spotify, youtube, spotify]);
    library.activate(id);
    expect(q.next()?.source).toBe("spotify");
    expect(q.state.base[0].source).toBe("youtube");
    expect(library.get(id).tracks.map(t => t.source)).toEqual(["spotify", "youtube"]);
    library.rename(id, "Mixed favourites");
    const restored = new Queue(migrate(JSON.parse(JSON.stringify(q.persisted()))));
    expect(restored.state.activePlaylistId).toBe(id);
    expect(restored.state.playlists[0].name).toBe("Mixed favourites");
    expect(restored.playing).toBe(false);
    expect(restored.next()?.source).toBe("youtube");
  });
  it("finishes current music and drains requests and personal music before resuming mixed rotation", () => {
    const q = new Queue(); const library = new Playlists(q.state);
    library.create(id, "Mix"); library.append(id, [spotify, youtube]); library.activate(id);
    q.next();
    q.add({ ...youtube, id: "request0001" });
    q.listen({ ...youtube, id: "personal001" });
    expect(q.current?.id).toBe(spotify.id);
    expect(q.next()?.id).toBe("request0001");
    expect(q.next()?.id).toBe("personal001");
    expect(q.next()?.id).toBe(youtube.id);
    expect(q.next()?.id).toBe(spotify.id);
    q.ban(key(youtube));
    expect(q.next()?.id).toBe(spotify.id);
  });
  it("updates active tracks without restarting current playback or changing other saved playlists", () => {
    const q = new Queue(); const library = new Playlists(q.state);
    library.create(id, "Mix"); library.append(id, [spotify, youtube]); library.activate(id); q.next();
    library.create(otherId, "Other"); library.append(otherId, [youtube]);
    library.move(id, 0, 1);
    expect(library.get(id).tracks[0].source).toBe("youtube");
    expect(q.state.base[0].source).toBe("youtube");
    library.remove(id, key(youtube));
    expect(q.state.base.map(key)).toEqual([key(spotify)]);
    expect(library.get(otherId).tracks).toHaveLength(1);
    library.delete(id);
    expect(q.current?.id).toBe(spotify.id);
    expect(q.state.activePlaylistId).toBeNull();
    expect(q.next()).toBeNull();
  });
  it("rejects invalid edits atomically and preserves older base playlists on migration", () => {
    const state = defaults(); const library = new Playlists(state);
    library.create(id, "Mix");
    expect(() => library.activate(id)).toThrow("Add some tracks");
    library.append(id, [youtube]);
    const before = structuredClone(state);
    expect(() => library.append(id, [{ ...spotify, duration: -1 }])).toThrow();
    expect(() => library.move(id, 0, 1)).toThrow();
    expect(() => library.rename(id, " ")).toThrow();
    expect(() => library.create(id, "Duplicate")).toThrow();
    expect(state).toEqual(before);
    const old: any = defaults(); delete old.playlists; delete old.activePlaylistId; old.base = [youtube];
    expect(migrate(old)).toMatchObject({ playlists: [], activePlaylistId: null, base: [youtube] });
    for (const command of [{ type: "playlistCreate", id: "bad", name: "Mix" }, { type: "playlistMove", id, from: -1, to: 0 }, { type: "playlistAdd", id, input: " " }]) expect(CommandSchema.safeParse(command).success).toBe(false);
    expect(() => migrate({ ...state, activePlaylistId: otherId })).toThrow();
  });
});
